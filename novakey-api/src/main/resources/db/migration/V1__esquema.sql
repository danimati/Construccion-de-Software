-- Esquema derivado de NovaKey_ERP_entidad_relacion.drawio.
-- Las restricciones CHECK protegen la integridad aunque falle una validación de la aplicación.

-- ---------- Recursos Humanos ----------
CREATE TABLE area (
    id_area BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE cargo (
    id_cargo     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_area      BIGINT NOT NULL REFERENCES area,
    nombre       VARCHAR(80) NOT NULL,
    salario_base DECIMAL(12,2) NOT NULL CHECK (salario_base >= 0)
);
CREATE TABLE empleado (
    id_empleado   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cargo      BIGINT NOT NULL REFERENCES cargo,
    documento     VARCHAR(20) NOT NULL UNIQUE,
    nombres       VARCHAR(80) NOT NULL,
    apellidos     VARCHAR(80) NOT NULL,
    email         VARCHAR(120),
    telefono      VARCHAR(20),
    fecha_ingreso DATE NOT NULL,
    estado        VARCHAR(20) NOT NULL CHECK (estado IN ('activo','vacaciones','retirado'))
);
CREATE TABLE horario (
    id_horario  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado BIGINT NOT NULL REFERENCES empleado,
    dia_semana  SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    hora_inicio TIME NOT NULL,
    hora_fin    TIME NOT NULL,
    CHECK (hora_inicio < hora_fin)
);
CREATE TABLE nomina (
    id_nomina      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo_inicio DATE NOT NULL UNIQUE,
    periodo_fin    DATE NOT NULL,
    fecha_pago     DATE NOT NULL,
    estado         VARCHAR(20) NOT NULL CHECK (estado IN ('borrador','pagada')),
    CHECK (periodo_inicio <= periodo_fin)
);
CREATE TABLE detalle_nomina (
    id_detalle_nomina BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nomina         BIGINT NOT NULL REFERENCES nomina,
    id_empleado       BIGINT NOT NULL REFERENCES empleado,
    salario_base      DECIMAL(12,2) NOT NULL,
    devengados        DECIMAL(12,2) NOT NULL CHECK (devengados >= 0),
    deducciones       DECIMAL(12,2) NOT NULL CHECK (deducciones >= 0),
    neto_pagar        DECIMAL(12,2) NOT NULL,
    UNIQUE (id_nomina, id_empleado)
);

-- ---------- Identidad y Accesos ----------
CREATE TABLE usuario (
    id_usuario    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado   BIGINT UNIQUE REFERENCES empleado,
    username      VARCHAR(50) NOT NULL UNIQUE,
    email         VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    activo        BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en     TIMESTAMP NOT NULL DEFAULT now()
);
CREATE TABLE rol (
    id_rol      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT
);
CREATE TABLE permiso (
    id_permiso  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(80) NOT NULL UNIQUE,
    modulo      VARCHAR(40) NOT NULL,
    descripcion TEXT
);
CREATE TABLE usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES usuario,
    id_rol     BIGINT NOT NULL REFERENCES rol,
    PRIMARY KEY (id_usuario, id_rol)
);
CREATE TABLE rol_permiso (
    id_rol     BIGINT NOT NULL REFERENCES rol,
    id_permiso BIGINT NOT NULL REFERENCES permiso,
    PRIMARY KEY (id_rol, id_permiso)
);

-- ---------- Inventario y Producción ----------
CREATE TABLE material (
    id_material    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(30) NOT NULL UNIQUE,
    nombre         VARCHAR(120) NOT NULL,
    unidad_medida  VARCHAR(10) NOT NULL,
    stock_actual   DECIMAL(12,3) NOT NULL CHECK (stock_actual >= 0),
    stock_minimo   DECIMAL(12,3) NOT NULL CHECK (stock_minimo >= 0),
    costo_unitario DECIMAL(12,2) NOT NULL CHECK (costo_unitario >= 0)
);
CREATE TABLE producto (
    id_producto  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          VARCHAR(30) NOT NULL UNIQUE,
    nombre       VARCHAR(120) NOT NULL,
    precio_venta DECIMAL(12,2) NOT NULL CHECK (precio_venta >= 0),
    stock_actual INT NOT NULL CHECK (stock_actual >= 0),
    activo       BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE lista_materiales (
    id_producto BIGINT NOT NULL REFERENCES producto,
    id_material BIGINT NOT NULL REFERENCES material,
    cantidad    DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (id_producto, id_material)
);
CREATE TABLE orden_produccion (
    id_orden_produccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto  BIGINT NOT NULL REFERENCES producto,
    id_usuario   BIGINT NOT NULL REFERENCES usuario,
    cantidad     INT NOT NULL CHECK (cantidad > 0),
    fecha_inicio DATE,
    fecha_fin    DATE,
    estado       VARCHAR(20) NOT NULL CHECK (estado IN ('planeada','en_proceso','terminada','cancelada')),
    -- Añadido al diagrama ER: unidades que superaron cada una de las seis estaciones de la línea.
    avance       INTEGER[] NOT NULL DEFAULT '{0,0,0,0,0,0}' CHECK (cardinality(avance) = 6)
);
CREATE TABLE consumo_material (
    id_consumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_produccion BIGINT NOT NULL REFERENCES orden_produccion,
    id_material BIGINT NOT NULL REFERENCES material,
    cantidad    DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
    fecha       TIMESTAMP NOT NULL
);
CREATE TABLE movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_material   BIGINT REFERENCES material,
    id_producto   BIGINT REFERENCES producto,
    id_usuario    BIGINT NOT NULL REFERENCES usuario,
    tipo          VARCHAR(30) NOT NULL CHECK (tipo IN ('entrada_compra','salida_produccion','entrada_produccion','salida_venta','devolucion_venta','ajuste')),
    cantidad      DECIMAL(12,3) NOT NULL,
    documento_ref VARCHAR(40) NOT NULL,
    fecha         TIMESTAMP NOT NULL,
    CHECK ((id_material IS NULL) <> (id_producto IS NULL))
);
CREATE INDEX movimiento_fecha_idx ON movimiento_inventario (id_movimiento DESC);

-- ---------- Compras ----------
CREATE TABLE proveedor (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit          VARCHAR(20) NOT NULL UNIQUE,
    razon_social VARCHAR(120) NOT NULL,
    contacto     VARCHAR(80),
    email        VARCHAR(120),
    telefono     VARCHAR(20)
);
CREATE TABLE orden_compra (
    id_orden_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor BIGINT NOT NULL REFERENCES proveedor,
    id_usuario   BIGINT NOT NULL REFERENCES usuario,
    fecha        DATE NOT NULL,
    estado       VARCHAR(20) NOT NULL CHECK (estado IN ('enviada','parcial','recibida','cancelada')),
    total        DECIMAL(14,2) NOT NULL CHECK (total >= 0)
);
CREATE TABLE detalle_orden_compra (
    id_detalle_oc BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra BIGINT NOT NULL REFERENCES orden_compra,
    id_material   BIGINT NOT NULL REFERENCES material,
    cantidad      DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
    cantidad_recibida DECIMAL(12,3) NOT NULL DEFAULT 0,
    precio_unitario DECIMAL(12,2) NOT NULL CHECK (precio_unitario >= 0),
    CHECK (cantidad_recibida BETWEEN 0 AND cantidad)
);
CREATE TABLE cuenta_por_pagar (
    id_cxp BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_compra BIGINT NOT NULL UNIQUE REFERENCES orden_compra,
    monto  DECIMAL(14,2) NOT NULL CHECK (monto >= 0),
    saldo  DECIMAL(14,2) NOT NULL CHECK (saldo >= 0),
    fecha_vencimiento DATE NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('abierta','pagada')),
    CHECK (saldo <= monto)
);

-- ---------- Ventas ----------
CREATE TABLE cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo       VARCHAR(10) NOT NULL CHECK (tipo IN ('corp','final')),
    documento  VARCHAR(20) NOT NULL UNIQUE,
    nombre     VARCHAR(120) NOT NULL,
    email      VARCHAR(120),
    telefono   VARCHAR(20),
    direccion  VARCHAR(150)
);
CREATE TABLE cotizacion (
    id_cotizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente,
    id_usuario BIGINT NOT NULL REFERENCES usuario,
    fecha      DATE NOT NULL,
    vigencia   DATE NOT NULL,
    estado     VARCHAR(20) NOT NULL CHECK (estado IN ('enviada','aceptada','rechazada')),
    total      DECIMAL(14,2) NOT NULL CHECK (total >= 0)
);
CREATE TABLE detalle_cotizacion (
    id_detalle_cot BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cotizacion BIGINT NOT NULL REFERENCES cotizacion,
    id_producto   BIGINT NOT NULL REFERENCES producto,
    cantidad      INT NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(12,2) NOT NULL CHECK (precio_unitario >= 0)
);
CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente,
    id_cotizacion BIGINT REFERENCES cotizacion,
    canal  VARCHAR(10) NOT NULL CHECK (canal IN ('directo','web')),
    fecha  TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('confirmado','en_preparacion','facturado','cancelado'))
);
CREATE TABLE detalle_pedido (
    id_detalle_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido   BIGINT NOT NULL REFERENCES pedido,
    id_producto BIGINT NOT NULL REFERENCES producto,
    cantidad    INT NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(12,2) NOT NULL CHECK (precio_unitario >= 0)
);
CREATE TABLE factura (
    id_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido  BIGINT NOT NULL UNIQUE REFERENCES pedido,
    numero     VARCHAR(20) NOT NULL UNIQUE,
    fecha      DATE NOT NULL,
    subtotal   DECIMAL(14,2) NOT NULL,
    impuestos  DECIMAL(14,2) NOT NULL,
    total      DECIMAL(14,2) NOT NULL,
    estado     VARCHAR(20) NOT NULL CHECK (estado IN ('emitida','pagada'))
);

CREATE TABLE unidad_producida (
    id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_produccion BIGINT NOT NULL REFERENCES orden_produccion,
    id_detalle_pedido BIGINT REFERENCES detalle_pedido,
    numero_serie VARCHAR(40) NOT NULL UNIQUE,
    resultado_calidad VARCHAR(20) NOT NULL CHECK (resultado_calidad IN ('aprobada','rechazada')),
    fecha_ensamblaje TIMESTAMP NOT NULL
);

-- Numeración que debe seguir siendo única con usuarios concurrentes.
CREATE SEQUENCE numero_serie_seq;
CREATE SEQUENCE numero_factura_seq;
